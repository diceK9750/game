#!/usr/bin/env python3
"""Embed the exact local shiritori SVGs in CSS to avoid blank panels.

Run `python -B tools/inline_shiritori_art.py --write` after changing an SVG;
without --write this checks that the checked-in CSS is up to date.
"""
import argparse
import base64
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT / 'shiritori-ui.css'
NAMES = ('daruma', 'top', 'ramune', 'zucchini', 'medaka', 'snow_crab',
         'blocks', 'parsley', 'mushroom', 'paint')
BEGIN = '/* BEGIN GENERATED SHIRITORI ART */'
END = '/* END GENERATED SHIRITORI ART */'


def generated(newline):
    lines = [BEGIN,
             '/* Generated by tools/inline_shiritori_art.py; SVG source files remain authoritative. */']
    sources = {}
    for name in NAMES:
        relative = f'assets/shiritori/{name}.svg'
        # Git stores these text SVGs with LF; normalize Windows checkouts so
        # generated CSS and CI checks remain identical on every platform.
        svg = (ROOT / relative).read_bytes().replace(b'\r\n', b'\n')
        encoded = base64.b64encode(svg).decode('ascii')
        sources[name] = f"url('data:image/svg+xml;base64,{encoded}')"
    lines.extend([
        '/* Source: assets/shiritori/daruma.svg */',
        f".sh-daruma {{ width: 1em; height: 1.2em; background: {sources['daruma']} center / contain no-repeat; }}",
        '/* Shared local pictures keep the board, dictionary and review recognizable',
        '   across emoji fonts; catalog IDs and saved reading keys stay unchanged. */',
        '.sh-art-top, .sh-art-ramune, .sh-art-zucchini,',
        '.sh-art-medaka, .sh-art-snow_crab, .sh-art-blocks, .sh-art-parsley, .sh-art-mushroom, .sh-art-paint {',
        '  display: inline-block; width: 1em; height: 1em;',
        '  background-position: center; background-size: contain; background-repeat: no-repeat;',
        '}',
    ])
    for name in NAMES[1:]:
        lines.extend([f'/* Source: assets/shiritori/{name}.svg */',
                      f'.sh-art-{name} {{ background-image: {sources[name]}; }}'])
    lines.append(END)
    return newline.join(lines)


def replacement(css):
    newline = '\r\n' if '\r\n' in css else '\n'
    if BEGIN in css or END in css:
        if css.count(BEGIN) != 1 or css.count(END) != 1:
            raise ValueError('Generated CSS markers are missing or duplicated')
        start = css.index(BEGIN)
        stop = css.index(END, start) + len(END)
    else:
        # One-time conversion of the original, source-linked CSS block.
        start = css.index('.sh-daruma {')
        stop = css.index('.sh-history-icon.sh-daruma', start)
    return css[:start] + generated(newline) + newline + css[stop:].lstrip('\r\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='update the CSS generated block')
    args = parser.parse_args()
    original = CSS.read_bytes().decode('utf-8')
    result = replacement(original)
    if result == original:
        print('Shiritori inline artwork matches source SVGs.')
        return 0
    if not args.write:
        print('Inline artwork differs from source SVGs; run with --write.', file=sys.stderr)
        return 1
    CSS.write_bytes(result.encode('utf-8'))
    print('Updated inline shiritori artwork.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
